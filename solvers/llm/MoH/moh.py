logger = logging.getLogger(__name__)

#: The utility assigned to anything that failed to run. Large enough to lose
#: every comparison, finite so the weighted mean in Eq. (2) stays a number.
FAILED = 1e6

class BudgetExhaustedError(Exception):
    """Raised when evaluation budget is spent to immediately terminate LLM search loops."""
    pass

#: Rejects actual use of the random modules rather than the substring "random",
#: so an identifier like `randomised_weight` survives. The task prompts forbid
#: randomness because a heuristic whose score changes between evaluations makes
#: both loops select on noise.
_RANDOM_USE = re.compile(
    r"(^|\W)(import\s+random|from\s+random\s+import|random\.\w|np\.random|"
    r"numpy\.random|default_rng|RandomState)")


class MoH:
    """Meta-optimizer of Heuristics."""

    def __init__(
        self,
        cfg: DictConfig,
        root_dir: str,
        heu_llm: BaseClient,
        meta_llm: Optional[BaseClient] = None,
        run_logger: Optional[RunLogger] = None,
    ) -> None:
        self.cfg = cfg
        self.root_dir = root_dir
        self.heu_llm = heu_llm
        self.meta_llm = meta_llm or heu_llm

        self.iteration = cfg.n_iterations
        self.improver_str = ""
        self.meta_utility_val = None

        self.problem_name = cfg.problem.problem_name
        sizes = [int(s) for s in cfg.problem.problem_size]
        if not sizes:
            raise ValueError(
                "cfg.problem.problem_size must list at least one instance size; "
                "MoH's subtasks are sizes (Eq. 2 weights them by size).")
        self.sizes = sizes
        self.subtask_list = [f"{self.problem_name}-{s}" for s in sizes]
        self.size_weights = np.array(sizes, dtype=float)

        self.subtask_pop = Pop(self.subtask_list, cfg.pop_size)
        self.improver_pop = Pop(["meta-optimizer"], cfg.pop_size)

        # Eval-call budget: per-subtask x N. null/-1 = unlimited.
        max_calls = cfg.get("max_eval_calls", None)
        self.max_eval_calls = (max_calls * len(self.subtask_list)
                               if max_calls and max_calls > 0 else None)
        self._total_eval_calls = 0
        self._budget_exhausted = False
        self._cur_iter = -1
        self._eval_counters: dict[tuple, int] = {}

        #: subtask -> the best (idea, code, utility) seen anywhere in the run.
        self.best_per_subtask: dict[str, dict] = {}
        self.best_improver: dict | None = None

        self.run_logger = run_logger or RunLogger()

        # eval.py runs as a subprocess with no Hydra context, so the data split
        # and the engine budget travel to it as environment variables. Set once,
        # here, from the config — never hardcoded in the task files.
        self.eval_env = dict(os.environ)
        self.eval_env["ATSP_DATA"] = str(cfg.data.name)
        self.eval_env["ATSP_EVAL_BUDGET"] = str(
            cfg.get("evaluation_budget", None) or self.problem_name)
        self.eval_env["PYTHONPATH"] = os.pathsep.join(
            p for p in [self.root_dir, REPO_ROOT, os.environ.get("PYTHONPATH", "")] if p)

        self.init_prompts()
        self.init_meta_improver()

    # =========================================================================
    # Initialisation
    # =========================================================================

    def init_prompts(self):
        self.meta_prompts = read_file_as_str(
            os.path.join(self.root_dir, "prompts", "meta", "desc.txt"))

        prompt_dir = os.path.join(self.root_dir, "prompts", self.problem_name)
        if not os.path.isdir(prompt_dir):
            available = sorted(d for d in os.listdir(os.path.join(self.root_dir, "prompts"))
                               if d not in ("meta", "helper"))
            raise FileNotFoundError(
                f"no prompts for task {self.problem_name!r}; available: {available}")
        self.subtask_form = read_file_as_str(os.path.join(prompt_dir, "desc.txt"))
        self.task_description = read_file_as_str(os.path.join(prompt_dir, "task.txt"))
        self.subtask_direction = read_file_as_str(os.path.join(prompt_dir, "plan.txt"))
        self.size_hint = read_file_as_str(os.path.join(prompt_dir, "size.txt"))

        self.system_check_prompt = read_file_as_str(
            os.path.join(self.root_dir, "prompts", "helper", "check_iter.txt"))

    def init_meta_improver(self):
        """Load ``I_0``, the seed meta-optimizer.

        ``cfg.meta_optimizer`` overrides it with any file exporting
        ``improve_algorithm`` — in particular a ``best_meta_optimizer.py`` from
        an earlier run, which is how the paper's inference stage reuses a
        trained optimizer on a task it was not trained on.
        """
        override = self.cfg.get("meta_optimizer", None)
        if override:
            # Hydra has already chdir'd into the run directory, so a path the
            # user typed relative to their shell no longer resolves. Try the
            # sensible anchors and say which were tried if none works.
            candidates = ([override] if os.path.isabs(override) else
                          [os.path.join(REPO_ROOT, override),
                           os.path.join(self.root_dir, override),
                           os.path.abspath(override)])
            path = next((c for c in candidates if os.path.isfile(c)), None)
            if path is None:
                raise FileNotFoundError(
                    f"meta_optimizer={override} does not exist. Tried: "
                    + ", ".join(candidates)
                    + ". Give a path relative to the repository root, e.g. "
                      "meta_optimizer=runs/llm/MoH/<task>/<timestamp>/"
                      "best_meta_optimizer.py, or use "
                      "python_scripts/llm/MoH/run_moh_atsp.py --inference, "
                      "which makes it absolute for you.")
            logger.info(f"Seeding the outer loop from {os.path.relpath(path, REPO_ROOT)}")
        else:
            path = os.path.join(self.root_dir, "problems", "meta", "seed_algorithm.py")
        self.seed_optimizer_path = path
        self.improver_str = read_file_as_str(path)
        self.algorithm_to_improve = self.improver_str

    # =========================================================================
    # Seed-population cache
    # =========================================================================

    def _solution_cache_path(self, subtask: str) -> str:
        """Where a subtask's seeded heuristic population is cached.

        Upstream wrote ``problems/<task>/solution_<subtask>.json`` inside the
        solver source tree, which makes every run dirty the working copy and
        makes two configs with different data silently share one cache. Here it
        is keyed by data config as well as by subtask, and lives under
        ``data/cache/`` with the rest of the repository's derived files.
        """
        directory = os.path.join(REPO_ROOT, "data", "cache", "moh",
                                 data_config_name(), self.problem_name)
        os.makedirs(directory, exist_ok=True)
        return os.path.join(directory, f"seed_pop_{subtask}.json")

    # =========================================================================
    # Task-level evaluation, via subprocess
    # =========================================================================

    def _run_code(self, algorithm_str: str, problem_type: str, mode: str,
                  stdout_path: str) -> subprocess.Popen:
        # 1. write the candidate to problems/<task>/gpt.py, which eval.py imports
        gpt_path = os.path.join(self.root_dir, "problems", self.problem_name, "gpt.py")
        with open(gpt_path, "w", encoding="utf-8") as f:
            f.write(ensure_numpy_import(algorithm_str) + "\n")

        # 2. launch eval.py; its last numeric stdout line is the utility
        eval_path = os.path.join(self.root_dir, "problems", self.problem_name, "eval.py")
        problem_size = int(problem_type.split("-")[-1])
        with open(stdout_path, "w", encoding="utf-8") as f:
            f.write("# ===== Heuristic Code =====\n")
            f.write(algorithm_str)
            f.write("\n# ===== Eval Output =====\n")
            f.flush()
            return subprocess.Popen(
                [sys.executable, "-u", eval_path, str(problem_size), self.root_dir,
                 mode, str(self.cfg.timeout)],
                stdout=f, stderr=f, cwd=self.root_dir, env=self.eval_env)

    def probe_heuristic(self, algorithm_str: str) -> bool:
        """Fast in-memory probing of candidate code on dummy test instances.

        Catches array shape mismatches, missing arguments, non-finite values, and
        dimension indexing errors in <1ms before launching subprocesses.
        """
        try:
            code = ensure_numpy_import(algorithm_str)
            ns = {"np": np, "numpy": np, "math": math, "random": random}
            exec(code, ns)
            func = ns.get("update_edge_distance")
            if not callable(func):
                return False
            for n in (5, 10):
                d = np.ones((n, n), dtype=float) - np.eye(n)
                tour = np.arange(n)
                used = np.zeros((n, n), dtype=int)
                res = func(d.copy(), tour, used)
                if not isinstance(res, np.ndarray) or res.shape != (n, n):
                    return False
                if not np.all(np.isfinite(res)):
                    return False
            return True
        except Exception as exc:
            logger.info(f"probe_heuristic caught error: {exc}")
            return False

    def evaluate_heuristic(self, algorithm_str: str, problem_type: str,
                           mode: str = "val") -> float:
        """``U_i(h, D_i)``: the mean optimality gap of one heuristic, in percent."""
        if not algorithm_str:
            logger.info(f"algorithm_str is {algorithm_str!r}, skipping")
            return FAILED
        if _RANDOM_USE.search(algorithm_str):
            logger.info("heuristic uses randomness; rejected (see prompts/*/desc.txt)")
            return FAILED
        if len(algorithm_str) < 30:
            logger.info("algorithm_str is too short to be a heuristic")
            return FAILED
        if not self.probe_heuristic(algorithm_str):
            logger.info("candidate failed fast in-memory probing check")
            return FAILED

        if self.max_eval_calls and self._total_eval_calls >= self.max_eval_calls:
            # Checked here, not only between iterations: seeding alone can
            # otherwise overshoot the budget by hundreds of calls.
            if not self._budget_exhausted:
                logger.warning(f"Evaluation budget spent ({self.max_eval_calls}); "
                               f"further candidates score {FAILED:g} and the run "
                               f"will stop immediately.")
                self._budget_exhausted = True
            raise BudgetExhaustedError(f"Evaluation budget spent ({self.max_eval_calls})")

        self._total_eval_calls += 1
        if self.max_eval_calls:
            logger.info(f"Eval call {self._total_eval_calls}/{self.max_eval_calls} "
                        f"({problem_type}, mode={mode})")

        key = (self._cur_iter, problem_type)
        self._eval_counters[key] = self._eval_counters.get(key, 0) + 1
        stdout_path = self.run_logger.evaluation_path(self._cur_iter, problem_type, mode)

        started = time.time()
        try:
            process = self._run_code(algorithm_str, problem_type, mode, stdout_path)
        except Exception as exc:
            logger.warning(f"could not launch the evaluation subprocess: {exc}")
            self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, FAILED,
                                           stdout_path, time.time() - started,
                                           "launch_failed", str(exc))
            return FAILED

        # The engine already stops itself at its configured time limit; this is
        # the hard kill for a candidate that ignores it (an infinite loop in the
        # heuristic itself). cfg.problem.timeout is per task.
        try:
            process.communicate(timeout=self.cfg.timeout)
        except subprocess.TimeoutExpired:
            process.kill()
            process.communicate()
            logger.warning(f"evaluation timed out after {self.cfg.timeout}s "
                           f"({problem_type}, mode={mode})")
            self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, FAILED,
                                           stdout_path, time.time() - started,
                                           "timeout")
            return FAILED

        try:
            with open(stdout_path, "r", encoding="utf-8", errors="replace") as f:
                stdout_str = f.read()
        except OSError as exc:
            self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, FAILED,
                                           stdout_path, time.time() - started,
                                           "unreadable", str(exc))
            return FAILED

        # Only the subprocess's own output is inspected: the file starts with the
        # candidate's source, and upstream's whole-file substring search meant a
        # heuristic with "error" in a comment was discarded whatever it scored.
        output = extract_eval_output(stdout_str)
        if "Traceback" in output:
            logger.warning(f"evaluation raised: {output.strip()[-400:]}")
            self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, FAILED,
                                           stdout_path, time.time() - started,
                                           "raised", output.strip()[-400:])
            return FAILED

        utility = parse_objective(stdout_str)
        if utility is None or not math.isfinite(utility):
            logger.warning("evaluation produced no parsable objective")
            self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, FAILED,
                                           stdout_path, time.time() - started,
                                           "unparsable")
            return FAILED

        seconds = time.time() - started
        logger.info(f"Eval {problem_type} mode={mode}: utility={utility:.4f} "
                    f"({seconds:.1f}s)")
        self.run_logger.log_evaluation(self._cur_iter, problem_type, mode, utility,
                                       stdout_path, seconds, "ok")
        return float(utility)

    # =========================================================================
    # Seeding the heuristic populations
    # =========================================================================

    def generate_directions(self, problem, size, cur_direction=None, seed=False,
                            solution=None):
        """Ask the LLM for high-level directions (Appendix D.3 of the paper)."""
        directions = []
        task_description = self.task_description

        if seed:
            extra_info = "" if not cur_direction else \
                f"Do not repeat any of the previously generated directions: {cur_direction}."
            message = (
                f"The problem is {problem} with corresponding size {size}. "
                f"According to the task description: {task_description} "
                f"Provide several high-level directions for generating the seed prompt, "
                f"each aimed at minimizing the utility as a result. {extra_info} "
                f"Format your response as a JSON codeblock below:\n"
                '{\n  "direction": [\n'
                '    {"content": "Your first piece of direction suggestion here."},\n'
                '    {"content": "Your second piece of direction suggestion here."},\n'
                '    {"content": "Your third piece of direction suggestion here."}\n'
                "  ]\n}")
        else:
            message = (f"The task is: {task_description}. Given current solution "
                       f"{solution['best_sol']} with utility {solution['utility']}. "
                       f"{self.subtask_direction}")

        expertise = ("You are an expert in the domain of optimization heuristics and "
                     "combinatorial optimization problems. Your task is to design "
                     "heuristics that can effectively solve optimization problems.")
        response = self.heu_llm.prompt(expertise, message, 0.7)
        payload = extract_code(response)
        try:
            data = json.loads(payload)
        except Exception as exc:
            logger.warning(f"could not parse the direction JSON ({exc}); asking again")
            retry = (f"There is an exception {exc} while parsing the json file "
                     f"{payload}, please check the json file and return a correct one.")
            payload = extract_code(self.heu_llm.prompt(
                "You are an expert in finding coding errors and debugging.", retry, 0.7))
            try:
                data = json.loads(payload)
            except Exception:
                logger.warning("still unparsable; skipping this direction round")
                return []

        for item in data.get("direction", []):
            content = item.get("content") if isinstance(item, dict) else item
            if content:
                directions.append(content)
        return directions

    def generate_seed_algorithm(self, formula_str, prob_type, threshold, t=0.7):
        """Fill ``H_i`` with heuristics that clear ``threshold``.

        Bounded, unlike upstream. ``cfg.seed_rounds`` caps the number of
        direction rounds and the threshold is relaxed by ``cfg.seed_relax``
        after each unproductive one, so a badly guessed threshold costs a
        warning rather than an unbounded spend. If the population is still
        short at the end, the run proceeds with what it has: MoH only needs a
        non-empty population to start, and the first inner loop will grow it.
        """
        problem, _, size = prob_type.rpartition("-")
        target = max(1, min(5, self.cfg.pop_size))
        max_rounds = int(self.cfg.get("seed_rounds", 4))
        relax = float(self.cfg.get("seed_relax", 1.5))

        cur_direction: list[str] = []
        role = ("You are an expert in the domain of optimization heuristics and "
                "combinatorial optimization problems. Your task is to design "
                "heuristics that can effectively solve optimization problems.")

        for round_index in range(max_rounds):
            if self.subtask_pop.get_subtask_size(prob_type) >= target:
                break
            if self._budget_exhausted:
                break

            directions = self.generate_directions(problem, size, cur_direction, seed=True)
            if not directions:
                continue

            for direction in directions:
                message = (
                    f"Write a function that will implement a Python algorithm to solve "
                    f"a problem as well as possible.\n"
                    f"The optimization problem is {problem} and the size you should "
                    f"focus on is {size}.\n"
                    f"The output function is formatted as follows:\n"
                    f"```python\n{formula_str}\n```\n"
                    f"You should develop the algorithm that follows the direction: "
                    f"{direction}. "
                    f"{self.size_hint.replace('{prob}', problem).replace('{size}', str(size))} "
                    f"First, describe your new algorithm and main steps in one sentence. "
                    f"The description must be inside a brace. "
                    f"Then, provide a Python function that implements the algorithm.")
                try:
                    response = self.heu_llm.prompt(role, message, temperature=t)
                    algorithm_str = clean_code(extract_code(response))
                    idea_str = extract_idea(response)
                    utility_score = self.evaluate_heuristic(algorithm_str, prob_type,
                                                            mode="val")
                    if utility_score < threshold:
                        self.subtask_pop.save_solution(prob_type, idea_str,
                                                       algorithm_str, utility_score)
                        self._note_best(prob_type, idea_str, algorithm_str, utility_score)
                except Exception as exc:
                    logger.warning(f"seed candidate failed: {exc}")
                if self.subtask_pop.get_subtask_size(prob_type) >= target:
                    break
                if self._budget_exhausted:
                    break

            cur_direction += directions
            if self.subtask_pop.get_subtask_size(prob_type) < target:
                old, threshold = threshold, threshold * relax
                logger.warning(
                    f"{prob_type}: only {self.subtask_pop.get_subtask_size(prob_type)}/"
                    f"{target} seed heuristics cleared utility < {old:g} after round "
                    f"{round_index + 1}/{max_rounds}; relaxing the threshold to "
                    f"{threshold:g}. Set cfg.problem.threshold from the seed "
                    f"heuristic's own score: bash scripts/llm/MoH/baselines.sh")

        if self.subtask_pop.get_subtask_size(prob_type) == 0:
            # Nothing survived. Fall back to the task's committed seed function
            # so the inner loop has something to improve rather than crashing on
            # an empty population.
            fallback = self._seed_function()
            score = self.evaluate_heuristic(fallback, prob_type, mode="val")
            self.subtask_pop.save_solution(prob_type, "task seed function", fallback,
                                           score)
            self._note_best(prob_type, "task seed function", fallback, score)
            logger.warning(f"{prob_type}: seeded from prompts/{self.problem_name}/"
                           f"seed_func.txt with utility {score:g}")

        return self.subtask_pop.get_random_solution(prob_type)

    def _seed_function(self) -> str:
        """The task's committed baseline heuristic, as a runnable source string."""
        path = os.path.join(self.root_dir, "prompts", self.problem_name, "seed_func.txt")
        return "import numpy as np\n\n" + read_file_as_str(path)

    def _get_threshold(self, subtask) -> float:
        """Seed-acceptance threshold for a subtask, from ``cfg.problem.threshold``."""
        size_key = int(subtask.split("-")[-1])
        table = self.cfg.problem.get("threshold", {}) or {}
        value = table.get(size_key, table.get(str(size_key), None))
        if value is None:
            value = self.cfg.problem.get("threshold_default", 25.0)
        return float(value)

    def read_base_algorithm(self, subtask):
        """Make sure ``H_i`` is non-empty, seeding or loading the cache as needed."""
        cache_path = self._solution_cache_path(subtask)

        if self.subtask_pop.get_subtask_size(subtask) == 0 and os.path.exists(cache_path):
            self.subtask_pop.load_subtask_from_file(subtask, cache_path)
            logger.info(f"{subtask}: loaded {self.subtask_pop.get_subtask_size(subtask)} "
                        f"cached seed heuristics from "
                        f"{os.path.relpath(cache_path, REPO_ROOT)}")

        if self.subtask_pop.get_subtask_size(subtask) < 3:
            self.generate_seed_algorithm(self.subtask_form, subtask,
                                         self._get_threshold(subtask))
            self.subtask_pop.save_subtask_to_file(subtask, cache_path)

        return self.subtask_pop.get_random_solution(subtask)

    # =========================================================================
    # Meta-level evaluation
    # =========================================================================

    def _note_best(self, subtask: str, idea, code, utility) -> None:
        """Track the best heuristic per subtask across the whole run.

        ``FAILED`` is excluded on purpose: it is the sentinel for "did not run",
        not a score. Without this, a run in which nothing worked would still
        write a ``best_heuristic.py`` — a broken heuristic presented as the
        result.
        """
        if code is None or utility is None or not math.isfinite(utility):
            return
        if utility >= FAILED:
            return
        current = self.best_per_subtask.get(subtask)
        if current is None or utility < current["utility"]:
            self.best_per_subtask[subtask] = {
                "idea": idea, "best_sol": code, "utility": float(utility),
                "iteration": self._cur_iter}

    def _make_subtask_utility(self, subtask):
        def utility(algorithm_str, idea=None, problem_type=None):
            problem_type = problem_type or subtask
            score = self.evaluate_heuristic(algorithm_str, problem_type, mode="val")
            self._note_best(problem_type, idea, algorithm_str, score)
            return score
        return utility

    def _compile_improver(self, improve_str: str):
        """Safely compile candidate optimizer code string into a callable function."""
        import math
        import random
        import json

        namespace = dict(globals())
        namespace.update({
            "math": math,
            "exp": math.exp,
            "log": math.log,
            "sqrt": math.sqrt,
            "np": np,
            "numpy": np,
            "json": json,
            "random": random,
            "expertise": (
                "You are an expert in the domain of designing meta optimization "
                "strategy and combinatorial optimization problems. Your task is to "
                "design heuristics that can effectively solve optimization problems."
            ),
        })
        exec(ensure_numpy_import(improve_str), namespace)
        func = namespace.get("improve_algorithm")
        if not callable(func):
            raise ValueError("the candidate defines no improve_algorithm")
        return func

    def get_improver(self, improve_str, subtask_str, subtask):
        """Run a candidate optimizer once on one subtask (the inner loop)."""
        try:
            improve_algorithm = self._compile_improver(improve_str)
            return improve_algorithm(
                copy.deepcopy(self.subtask_pop), self._make_subtask_utility(subtask),
                self.heu_llm, subtask_str, subtask)
        except Exception as exc:
            logger.warning(f"candidate optimizer failed on {subtask}: {exc}")
            logger.debug("", exc_info=True)
            return exc


    def meta_utility(self, improve_str: str, idea: str, task: str = None) -> float:
        """``U(I)`` — Eq. (2): the size-weighted mean utility of one optimizer."""
        if not improve_str:
            logger.info("improve_str is empty, skipping")
            return FAILED

        self.run_logger.save_candidate_improver(improve_str, idea)

        # An optimizer that never prompts the model is not an optimizer: it is a
        # local edit of the code it was handed, which the meta prompt forbids
        # because such edits invalidate the heuristic more often than they
        # improve it. This check is what keeps the outer loop searching over
        # *strategies* rather than over string manipulation.
        if ("language_model.prompt" not in improve_str
                and "language_model.prompt_batch" not in improve_str):
            logger.info("candidate optimizer never prompts the model; rejected")
            self.run_logger.save_candidate_improver(
                improve_str, idea, note="rejected: no prompting step")
            return FAILED

        # Loop-depth audit (Appendix D.1): a candidate whose outer loop runs more
        # than `max_optimizer_iterations` times would spend the whole evaluation
        # budget in one invocation.
        try:
            verdict = self.meta_llm.prompt(
                "You will act as a professional coder and analyze a given function "
                "provided as a string.",
                f"Check if the following Python function definition contains a while "
                f"loop or loop structure that executes more than "
                f"{self.cfg.max_optimizer_iterations} iterations. Reply ONLY in "
                f"JSON: {{\"loop_count\": N}}.",
                0.0)
            data = json.loads(extract_code(verdict))
            count = int(data.get("loop_count", 0))
            if count > self.cfg.max_optimizer_iterations:
                logger.info(f"candidate optimizer loops {count} times (> "
                            f"{self.cfg.max_optimizer_iterations}); rejected")
                self.run_logger.save_candidate_improver(
                    improve_str, idea, note=f"rejected: loops {count} times")
                return FAILED
        except Exception:
            pass  # parser failed; let it run and trust the evaluation cap

        # Score the optimizer across all downstream subtasks (Section 3.2, Eq. 2)
        utilities = []
        for subtask in self.subtask_list:
            if self._budget_exhausted:
                break
            self.read_base_algorithm(subtask)
            result = self.get_improver(improve_str, self.subtask_form, subtask)
            if isinstance(result, Exception):
                logger.warning(f"candidate optimizer failed on {subtask}: {result}")
                utilities.append(FAILED)
                continue
            idea_r, code, utility = result
            if not code or utility is None or not math.isfinite(utility):
                utilities.append(FAILED)
            else:
                utilities.append(utility)

        if not utilities or any(u >= FAILED for u in utilities):
            return FAILED

        # Size-weighted mean gap: Eq. (2), w_i = s_i / sum_j s_j
        weights = self.size_weights[:len(utilities)]
        weighted = float(np.sum(np.array(utilities) * weights) / np.sum(weights))
        logger.info(f"Meta utility U(I) = {weighted:.4f} across {len(utilities)} subtasks")
        return weighted

    # =========================================================================
    # Algorithm 1: The outer loop
    # =========================================================================

    def get_seed(self):
        """Initialize populations and evaluate the seed meta-optimizer I_0."""
        for subtask in self.subtask_list:
            self.read_base_algorithm(subtask)

        if self.cfg.get("mode", "train") == "inference":
            self.meta_utility_val = None
            return

        logger.info("Evaluating seed meta-optimizer I_0 ...")
        seed_idea = "seed optimizer"
        self.improver_pop.save_solution("meta-optimizer", seed_idea,
                                        self.improver_str, FAILED)
        self.meta_utility_val = self.meta_utility(self.improver_str, seed_idea)
        if self.meta_utility_val >= FAILED:
            logger.warning(
                "Seed meta-optimizer scored FAILED — check whether evaluations are "
                "failing — look at evaluations/index.jsonl for the status of "
                "each attempt. The outer loop will still run, but it has no "
                "baseline to improve on.")
        else:
            logger.info(f"Seed optimizer meta-utility: {self.meta_utility_val}")

    def try_improvement(self, improve_algorithm_func, previous_algo):
        """One outer-loop step: ``I*_{t-1}`` proposes, ``U(.)`` decides.

        Returns ``(improved, code, idea, driver)``. ``improved`` is True only
        when the proposal is *strictly better* than the incumbent — not merely
        when it ran. A generated optimizer that finds nothing returns the
        population's current best unchanged, and calling that "accepted" would
        make every iteration of a stalled run look like progress in
        ``progress.jsonl``, which is the one file you read to tell the two
        apart.
        """
        new_algorithm_str = None
        try:
            new_idea, new_algorithm_str, new_utility = improve_algorithm_func(
                copy.deepcopy(self.improver_pop), self.meta_utility, self.meta_llm,
                self.meta_prompts, "meta-optimizer")

            # `if not new_utility` was upstream's test; a meta-utility of exactly
            # 0.0 is reachable on ATSP (every instance solved to optimality at
            # n=50) and was being thrown away as an error.
            if new_utility is None or not math.isfinite(new_utility):
                raise ValueError(f"candidate returned utility {new_utility!r}")
            if not new_algorithm_str:
                raise ValueError("candidate returned no code")
            # FAILED means the candidate did not run at all — every subtask
            # rejected it, or it produced no code. Adopting it would make it
            # I*_t and hand the next iteration a broken starting point.
            if new_utility >= FAILED:
                raise ValueError("candidate scored the failure sentinel; "
                                 "it did not run on any subtask")

            # Store the pair that was actually scored. Upstream stored the *old*
            # code under the *new* idea, so the population's ideas and code
            # drifted apart over a run.
            self.improver_pop.save_solution("meta-optimizer", new_idea,
                                            new_algorithm_str, new_utility)

            improved = (self.meta_utility_val is None
                        or new_utility < self.meta_utility_val - 1e-12)
            if improved:
                self.meta_utility_val = float(new_utility)
                self.best_improver = {"idea": new_idea, "best_sol": new_algorithm_str,
                                      "utility": float(new_utility),
                                      "iteration": self._cur_iter}
                logger.info(f"new best optimizer: U(I) = {new_utility:.4f}")
            else:
                logger.info(f"candidate scored {new_utility:.4f}, not better than the "
                            f"incumbent's {self.meta_utility_val:.4f}")
            return improved, new_algorithm_str, new_idea, improve_algorithm_func

        except BudgetExhaustedError:
            raise
        except Exception as exc:
            logger.warning(f"outer-loop step failed: {exc}")
            logger.debug("", exc_info=True)
            return False, new_algorithm_str, "", previous_algo

    def run_meta_optimizer(self):
        """Algorithm 1: T iterations of optimizer design over N subtasks."""
        self.get_seed()

        from problems.meta.seed_algorithm_improved import improve_algorithm as first
        improver = first
        previous_algorithm = improver

        for cur_iter in range(self.iteration):
            self._cur_iter = cur_iter
            logger.info(f"=== outer-loop iteration {cur_iter}/{self.iteration - 1} ===")

            try:
                improved, new_algorithm_str, new_idea, improver = self.try_improvement(
                    improver, previous_algorithm)
            except BudgetExhaustedError:
                logger.info(f"Evaluation budget spent ({self.max_eval_calls}); stopping "
                            f"outer loop at iteration {cur_iter}.")
                break

            # Algorithm 1, step (c): I*_t is the best individual in
            # P ∪ {candidates}, whether that is this iteration's proposal or the
            # incumbent it failed to beat.
            accepted = bool(improved and new_algorithm_str)
            if accepted:
                logger.info("candidate optimizer accepted; it becomes I*_t")
                self.improver_str = new_algorithm_str
                self.algorithm_to_improve = new_algorithm_str
                previous_algorithm = improver
                try:
                    improver = self._compile_improver(self.improver_str)
                except Exception as exc:
                    logger.warning(f"could not compile accepted optimizer ({exc})")
            else:
                logger.info("no improvement this iteration; I*_t stays the best "
                            "optimizer in the population")
                best = self.improver_pop.get_best_solution("meta-optimizer")
                self.improver_str = best["best_sol"]
                try:
                    improver = self._compile_improver(best["best_sol"])
                except Exception as exc:
                    logger.warning(f"could not restore the best optimizer ({exc}); "
                                   f"continuing with the previous one")

            self.run_logger.log_meta_utility(cur_iter, self.meta_utility_val,
                                             accepted=accepted,
                                             eval_calls=self._total_eval_calls)
            self.run_logger.save_iteration(
                cur_iter, self.improver_pop, self.subtask_pop,
                improver_code=self.improver_str if accepted else None,
                improver_idea=new_idea if accepted else "")
            self.run_logger.log_progress({
                "iteration": cur_iter, "phase": "outer",
                "meta_utility": self.meta_utility_val, "accepted": accepted,
                "best_so_far": self.best_improver["utility"] if self.best_improver else None,
                "eval_calls": self._total_eval_calls,
                "subtask_best": {s: v["utility"] for s, v in self.best_per_subtask.items()},
            })

            if self.max_eval_calls and self._total_eval_calls >= self.max_eval_calls:
                logger.info(f"Evaluation budget spent ({self.max_eval_calls}); stopping "
                            f"after iteration {cur_iter}.")
                break

        logger.info("Finished all outer-loop iterations")

    def run_inference(self):
        """The paper's inference stage: apply a trained ``I*_T``, no outer loop.

        Section 3.2, last paragraph: "During inference, the meta-optimizer
        ``I*_T`` can be deployed on new tasks that differ from those encountered
        during training, such as tasks with larger problem sizes. By performing
        several rounds of heuristic design using ``I*_T``, MoH can yield an
        effective heuristic tailored to this task."

        So this runs the inner loop only, ``n_iterations`` times, on whatever
        subtasks the problem config names — which is how you take an optimizer
        trained on n=50/100 and point it at n=400.
        """
        logger.info(f"Inference mode: {self.iteration} rounds with the optimizer from "
                    f"{os.path.relpath(self.seed_optimizer_path, REPO_ROOT)}")
        namespace = dict(globals())
        exec(self.improver_str, namespace)
        improve_algorithm = namespace.get("improve_algorithm")
        if not callable(improve_algorithm):
            raise ValueError(f"{self.seed_optimizer_path} defines no improve_algorithm")

        for cur_iter in range(self.iteration):
            self._cur_iter = cur_iter
            logger.info(f"=== inference round {cur_iter}/{self.iteration - 1} ===")
            for subtask in self.subtask_list:
                self.read_base_algorithm(subtask)
                result = self.get_improver(self.improver_str, self.subtask_form, subtask)
                if isinstance(result, Exception):
                    continue
                idea_r, code, utility = result
                if not code or utility is None or not math.isfinite(utility):
                    continue
                self.subtask_pop.save_solution(subtask, idea_r, code, utility)
                self._note_best(subtask, idea_r, code, utility)
                self.run_logger.log_utility(cur_iter, subtask, utility)

            self.run_logger.save_iteration(cur_iter, self.improver_pop, self.subtask_pop)
            self.run_logger.log_progress({
                "iteration": cur_iter, "phase": "inference",
                "eval_calls": self._total_eval_calls,
                "subtask_best": {s: v["utility"] for s, v in self.best_per_subtask.items()},
            })
            if self.max_eval_calls and self._total_eval_calls >= self.max_eval_calls:
                logger.info(f"Evaluation budget spent ({self.max_eval_calls}); stopping.")
                break

        logger.info("Finished inference")

    def run(self):
        if str(self.cfg.get("mode", "train")).lower() == "inference":
            self.run_inference()
        else:
            self.run_meta_optimizer()

