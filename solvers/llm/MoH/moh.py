"""MoH — Meta-optimization of Heuristics, retargeted to ATSP.

Implements Algorithm 1 of *Generalizable Heuristic Generation Through LLMs with
Meta-Optimization* (ICLR 2026) on the Asymmetric Travelling Salesman Problem.
The structure is upstream's and is deliberately unchanged:

**Outer loop — optimizer design.** The current meta-optimizer ``I*_{t-1}`` is
invoked on the *optimizer* population ``P`` to write M candidate
heuristic-optimizers. Each is a Python function ``improve_algorithm`` with the
signature in Figure 3 of the paper, generated by the LLM, and each is scored by
:meth:`MoH.meta_utility`. The best becomes ``I*_t``. Because the optimizer and
the heuristics it designs share one functional template, the meta-optimizer can
be applied to itself — the "(self-)invocation" the paper's abstract refers to,
and the reason ``P`` and ``H_i`` are the same :class:`Pop` class.

**Inner loop — heuristic design.** Each candidate optimizer is run once per
downstream subtask, where it evolves that subtask's heuristic population ``H_i``
and returns the best heuristic it found. The subtask utilities are combined
with the size weighting of Eq. (2), ``w_i = s_i / sum_j s_j``, into the
optimizer's utility ``U(I)``.

What changed for ATSP
---------------------
Only the things that had to:

* **The downstream problem.** TSP-GLS becomes ``atsp_gls`` / ``atsp_kgls`` /
  ``atsp_constructive`` on directed cost matrices, evaluated through the same
  engines every other framework in this repository uses. The subtasks are still
  sizes, exactly as TSP20/50/100/200 are in the paper.
* **Where the settings live.** Populations, budgets, thresholds, data splits and
  models are Hydra config under ``configs/llm/MoH/cfg/``, not constants here.
* **Where a run is written.** ``runs/llm/MoH/<problem>/<timestamp>/``, with the
  same log, trace and summary files the other frameworks produce.

Fixes to upstream, each of which cost a run rather than a result:

1. ``generate_seed_algorithm`` looped ``while cur_pop_size < 5`` with no bound.
   If no sampled heuristic ever cleared the acceptance threshold — which is what
   happens the first time you point it at a new problem and guess the threshold
   — it called the API forever. It is now bounded, relaxes the threshold between
   rounds, and says so in the log.
2. ``try_improvement`` treated a utility of ``0`` as failure (``if not
   new_utility``). On ATSP a gap of exactly 0.000% is common at n=50, so the
   best possible result was discarded as an error. It now checks for
   ``None``/``NaN``.
3. ``try_improvement`` stored the *old* optimizer code under the *new* idea, so
   the population's ideas and code drifted apart. It stores the pair it scored.
4. The evaluation output was scanned for the substring ``"Error"`` across the
   whole log — which begins with the candidate's own source, so a heuristic with
   ``error`` in a comment was thrown away no matter how it scored. Only the
   subprocess's own output is scanned now.
5. The determinism guard rejected any heuristic whose source contained the
   substring ``"random"``, including identifiers like ``randomised_weight``. It
   now looks for actual uses of the random modules.
6. Evaluation budget was checked only between outer iterations, so seeding could
   overshoot it by hundreds of calls. It is checked at every evaluation.
"""

